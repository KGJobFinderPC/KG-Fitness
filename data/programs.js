const FITNESS_PROGRAMS = {

    beginner: {

        "Weight Loss":
            createProgram("Weight Loss"),

        "Muscle Building":
            createProgram("Muscle Building"),

        "Strength":
            createProgram("Strength"),

        "Mobility & Flexibility":
            createProgram("Mobility & Flexibility")
    }

};


/* =========================================================
   GET FITNESS PROGRAM
   ========================================================= */

export function getFitnessProgram(
    level,
    goal
) {

    const normalizedLevel =
        level || "beginner";


    const normalizedGoal =
        goal || "Weight Loss";


    if (
        FITNESS_PROGRAMS[
            normalizedLevel
        ] &&
        FITNESS_PROGRAMS[
            normalizedLevel
        ][normalizedGoal]
    ) {

        return FITNESS_PROGRAMS[
            normalizedLevel
        ][normalizedGoal];
    }


    return FITNESS_PROGRAMS.beginner[
        "Weight Loss"
    ];
}


/* =========================================================
   GET WORKOUT DAY
   ========================================================= */

export function getWorkoutDay(
    level,
    goal,
    dayNumber
) {

    const program =
        getFitnessProgram(
            level,
            goal
        );


    if (
        !program ||
        !program.days
    ) {
        return null;
    }


    return program.days[
        Number(dayNumber)
    ] || null;
}