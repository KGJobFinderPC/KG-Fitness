/* =========================================================
   REP PATTERNS
   ========================================================= */

function getRepPattern(goal, week) {

    if (goal === "Strength") {

        if (week <= 4) {
            return "8 / 10 / 12";
        }

        if (week <= 8) {
            return "9 / 11 / 13";
        }

        return "10 / 12 / 14";
    }


    if (goal === "Weight Loss") {

        if (week <= 4) {
            return "12 / 14 / 16";
        }

        if (week <= 8) {
            return "13 / 15 / 17";
        }

        return "14 / 16 / 18";
    }


    if (goal === "Mobility & Flexibility") {
        return "10 / 12 / 14";
    }


    /* Muscle Building */

    if (week <= 4) {
        return "10 / 12 / 14";
    }

    if (week <= 8) {
        return "11 / 13 / 15";
    }

    return "12 / 14 / 16";
}


/* =========================================================
   REST
   ========================================================= */

function getRest(goal) {

    if (goal === "Strength") {
        return "90 sec";
    }

    if (goal === "Weight Loss") {
        return "45 sec";
    }

    if (goal === "Mobility & Flexibility") {
        return "30 sec";
    }

    return "60 sec";
}


/* =========================================================
   DETERMINISTIC ROTATION
   ========================================================= */

function getRotatedExercise(group, week) {

    const exercises = group.exercises;

    const index =
        ((week - 1) * 3) % exercises.length;

    return exercises[index];
}


/* =========================================================
   GET THREE DIFFERENT EXERCISES
   One from each muscle/equipment group.
   ========================================================= */

function chooseExercises(theme, week) {

    const selected = [];

    theme.groups.forEach(group => {

        const exercises =
            group.exercises;

        const index =
            ((week - 1) * 3) %
            exercises.length;

        selected.push(
            exercises[index]
        );
    });


    /*
       Some themes have exactly
       3 groups = exactly 3 exercises.
    */

    return selected.slice(0, 3);
}


/* =========================================================
   CREATE WORKOUT DAY
   ========================================================= */

function createWorkoutDay(
    dayNumber,
    theme,
    week,
    goal
) {

    const progression =
        PROGRESSION[week - 1] ||
        PROGRESSION[PROGRESSION.length - 1];


    const reps =
        getRepPattern(
            goal,
            week
        );


    const rest =
        getRest(goal);


    const exercises =
        chooseExercises(
            theme,
            week
        );


    return {

        day: dayNumber,

        week: week,

        title:
            `${theme.title} - Week ${week}`,

        description:
            `${theme.focus}. Complete all three exercises with controlled technique.`,

        duration:
            goal === "Mobility & Flexibility"
                ? "30-40 min"
                : "45-60 min",

        focus:
            theme.focus,

        progressionNote:
            progression.note,

        weightGuidance:
            "Start with a weight you feel you can control safely. Increase the weight gradually only when you can complete all repetitions with good form. The next training cycle can use slightly more resistance if appropriate.",

        exercises:
            exercises.map(exercise => ({

                name:
                    exercise.name,

                muscle:
                    exercise.muscle,

                equipment:
                    exercise.equipment,

                sets:
                    3,

                reps:
                    reps,

                rest:
                    rest

            }))
    };
}


/* =========================================================
   BUILD 90 DAYS
   ========================================================= */

function build90Days(goal) {

    const days = {};


    for (
        let day = 1;
        day <= 90;
        day++
    ) {

        const week =
            Math.floor(
                (day - 1) / 7
            ) + 1;


        const dayOfWeek =
            ((day - 1) % 7);


        const theme =
            WEEKLY_FOCUS[dayOfWeek];


        days[day] =
            createWorkoutDay(
                day,
                theme,
                week,
                goal
            );
    }


    return days;
}


/* =========================================================
   PROGRAM BUILDER
   ========================================================= */

function createProgram(goal) {

    return {

        name:
            `KG Fitness 90 Day - ${goal}`,

        duration:
            "90 Days",

        goal:
            goal,

        days:
            build90Days(goal)
    };
}


